create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  description text not null check (char_length(description) between 1 and 1500),
  category text not null,
  location text not null check (char_length(location) between 1 and 180),
  photo_url text,
  status text not null default 'Pending' check (status in ('Pending','In Progress','Resolved')),
  created_at timestamptz not null default now()
);
alter table public.reports enable row level security;
grant select, insert, update, delete on public.reports to authenticated;
grant usage, select on sequence public.reports_id_seq to authenticated;

create policy "Users can read their own reports"
on public.reports for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can create their own reports"
on public.reports for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can update their own reports"
on public.reports for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users can delete their own reports"
on public.reports for delete to authenticated
using ((select auth.uid()) = user_id);
